def build_freestanding_target_writes(active_freestanding_weapon_checks): # We control freestanding items by utilizing when their model is visible to the player kinda by draw distance load ins
    count = len(active_freestanding_weapon_checks) # Counts how many active freestanding weapons this mission has
    writes = []  

    writes.append((FREESTANDING_TARGET_COUNT_ADDRESS, u32_bytes(count), "RDRAM")) # Writes the count to 0x7F1C4

    for index, check in enumerate(active_freestanding_weapon_checks): # enumerate gives us indecies 0,1,2 and weapon id will write to the corresponding slot
        target_address = FREESTANDING_TARGET_LIST_ADDRESS + index * FREESTANDING_TARGET_ENTRY_SIZE
        writes.append((target_address, u32_bytes(check["weapon_id"]), "RDRAM"))

    return writes

# Weapon Loadout Defs

def count_received_items(items_received): # how many of each AP item id the player owns
    counts = {}
    for item in items_received:     # loop through received items
        item_id = item.item
        if item_id not in counts:   # if this item isn't already in the list
            counts[item_id] = 0     # add the item and assign to 0
        counts[item_id] += 1        # increment the count for this item if it's already in the list
    return counts 

def resolve_owned_weapons(counts):  # Resolve non-progressive weapon loadouts
    owned_weapon_items = []
    for item_id in WEAPON_ITEM_DEFS:
        if item_id in counts:
            owned_weapon_items.append(item_id)
    return owned_weapon_items

def expand_progressive_weapons(counts, owned_weapon_items):
    progressive_count = counts.get(PROGRESSIVE_GUN_BASE_ITEM_ID, 0) # Get the progressive weapon count 

    for item_id in PROGRESSIVE_GUN_ITEM_IDS[:progressive_count]:    # Loop through the progressive weapon item IDs
        if item_id not in owned_weapon_items:                       # If the item is not already in the owned weapon items list
            owned_weapon_items.append(item_id)                      # Add the item to the owned weapon items list

    return owned_weapon_items

def build_mission_start_weapon_loadout(owned_weapon_items):
    loadout = []

    for item_id in owned_weapon_items:          # Loop through the owned weapon items
        weapon_def = WEAPON_ITEM_DEFS[item_id]  # Get the weapon def from the item ID
        loadout.append({
            "item_id": item_id,                             # The AP item ID
            "weapon_id": weapon_def["weapon_id"],           # The AP Weapon ID
            "ammo_offset": weapon_def.get("ammo_offset"),   # The in-game address offset (use get() for case there is none)
            "ammo_grant": weapon_def.get("ammo_grant"),     # This is how much ammo is given at mission start
            "ammo_max": weapon_def.get("ammo_max"),         # Maximum ammo player is currently allowed
        })

    return loadout

def build_mission_start_gadget_ids(mission, counts):
    owned_gadget_ids = []                   # ids of gadgets the player has

    for ap_id, gadget_def in client_data.LOADOUT_GADGETS.items():   # Example: ap_id = 17330000 || gadget_def = {"item_name": "Covert Modem","item_id": 47,}
        if ap_id in counts:                                         # Example: counts = {17330000: 1, 17330004: 1, 17330003: 1}
            owned_gadget_ids.append(gadget_def["item_id"])          # Example: 17330000 is in both so add that gadget def's id ("item_id": 47,) into "owned_gadget_ids"

    gadget_ids = []

    for game_id in sorted(mission["base_loadout_ids"]):             # mission "Dam" has "base_loadout_ids": {5, 47}, ALSO we're sorting so that they're in the games expected stable order
        if game_id in owned_gadget_ids:                             # 47 is in both base_load_out id for Dam, and also in the player's AP items
            gadget_ids.append(game_id)                              # Add it to gadget_ids
    return gadget_ids                                               # Return gadget_ids

def build_startup_inventory_entries(loadout, gadget_ids, max_items): 
    
    # This function prepares the list of items to be written at the moment of loadout.  
    # This is tricky because we want to preserve memory to avoid pissing off the fragile code here, 
    # doing this wrong causes a crash at level start.

    # To preserve cycling through weapons, we need to construct the inventory like it naturally loads in game.
    # That is FIRST weapons, LAST gadgets. And if it exists already in the base loadout DON'T TOUCH IT.
    # Gadgets do NOT like to be written into inventory, but guns seem to be okay.

    # We also have a maximum number of items bond can hold in memory so we handle overflow here.
    # The rule I've set is, if we exceed max_items, start deleting the earliest weapon_ids until it fits.
    # This would just mean losing hunting knife first rather than clipping the higher number ids.

    # Here's where this function happens after lua sends loadout ready flag:
    # 1. Read current inventory snaphot (read_inventory_snapshot)
    # 2. Build AP weapon and gadget loadout (build_mission_start_weapon_loadout and build_mission_start_gadget_ids)
    # 3. Client calls THIS FUNCTION to return the exact ordered inventory list
    # 4. Client will then convert the list into memory writes, and then write the new inventory and clear the mailbox

### 1. Build Weapon Groups ###

    weapon_groups = []
    used_ids = set()
    
    slappers_entry = {"type": INV_ITEM_WEAPON, "weapon_id": ITEM_SLAPPERS, "left_weapon_id": 0}
    used_ids.add(ITEM_SLAPPERS)

    for weapon in sorted(loadout, key=lambda weapon: weapon["weapon_id"]):  # Sort the loadout by weapon_id to ensure a stable cycling order
   
        group = []                                                          # temp group for this weapon and its extra_inventory_ids
        weapon_id = weapon["weapon_id"]

        if weapon_id not in used_ids:           # Only add this weapon if we haven't already added it from a previous loadout entry with the same weapon_id (e.g. from progressive weapons sharing the same weapon_id)
            group.append({
                "type": INV_ITEM_WEAPON,
                "weapon_id": weapon_id,
                "left_weapon_id": 0,
            })
            used_ids.add(weapon_id)                             # mark this weapon_id as used so we don't add it again if it's duplicated in the loadout
        
        weapon_def = WEAPON_ITEM_DEFS.get(weapon["item_id"])    # Look up this AP weapon's definition

        extra_ids = weapon_def.get("extra_inventory_ids", [])   # extra weapon ids tied to this weapon, like Remote Mine adding trigger 30

        for extra_id in extra_ids:
            if extra_id not in used_ids:                        # Only add this extra inventory ID if we haven't already added it from a previous loadout entry
                group.append({
                    "type": INV_ITEM_WEAPON,
                    "weapon_id": extra_id,
                    "left_weapon_id": 0,
                })
                used_ids.add(extra_id)                          # mark this extra inventory ID as used so we don't add it again if it's duplicated in the loadout
        if group:                                               # If group is not empty, add it to weapon_groups
            weapon_groups.append(group)

### 2. Build Gadget Entries ##

    gadget_entries = []
        
    for gadget_id in gadget_ids:
        gadget_entries.append({
            "type": INV_ITEM_WEAPON,                            # startup gadgets use the same inventory entry type "INV_ITEM_WEAPON"
            "weapon_id": gadget_id,
            "left_weapon_id": 0,
        })

### 3. Handle Max Item Overflow ##

    total_entries = 1 + sum(len(group) for group in weapon_groups) + len(gadget_entries)        # Calculates the total of items you have to be loaded out plus slappers

    while total_entries > max_items and weapon_groups:                                          # If there's not enough room for all the weapons in memory
        weapon_groups.pop(0)                                                                    # remove the first group, aka the weakest guns in inventoy
        total_entries = 1 + sum(len(group) for group in weapon_groups) + len(gadget_entries)    # recalculate total_entries for next loop, plus one to account for slappers

    loadout_items = [slappers_entry]                                                            # This block puts the final list together in the correct order and with slappers included.
    for group in weapon_groups:
        loadout_items.extend(group)
    loadout_items.extend(gadget_entries)
    
    return loadout_items

def build_startup_inventory_writes(snapshot, startup_entries, bonddata_pointer): # compile the list of actual literal RAM writes to the game
    # format for each write = (address, bytes, "RDRAM")
    # write (type, weapon_id, left_weapon_id, next pointer, previous pointer)
    # The inventory list is circular: slot 0 goes "next" to slot 1, then the last slot goes "next" back to 0. 0 points "previous" to the last slot

    writes = []                                     # store the writes
    pool_pointer = snapshot["pool_pointer"]         # where the slot begins
    max_items = snapshot["max_items"]               # how many slots exist
    entry_count = len(startup_entries)              # how many entries we are trying to write
    
    # empty slot tuple, Just -1,0,0,0,0 at the right offsets for an empty weapon slot.
    empty_slot_fields = [(0x00, s32_bytes(INV_ITEM_NONE)),(0x04, u32_bytes(0)),(0x08, u32_bytes(0)),(0x0C, pointer_bytes(0)),(0x10, pointer_bytes(0)),]

# This first block writes the first three slots: The actual data from the item
# Example single item: {"type": INV_ITEM_WEAPON, "weapon_id": 7, "left_weapon_id": 0}
 
    for slot_index, entry in enumerate(startup_entries):            # use enumerate so we can get both index and value of each dictionary in the list of entries
        slot_address = pool_pointer + slot_index * INV_ITEM_SIZE    # where in the game's RAM we're performing the write
        fields = ["type", "weapon_id", "left_weapon_id"]            # this saves a few lines so I don't have to copy the block for every fucking one of these
        for field_index, field_name in enumerate(fields):           # we enumerate each field so we can get field_index and add an offset each iteration
            address = slot_address + (field_index * 4)              # the offset is every 4 bytes so this just keeps iterating every 4 spots every loop
            value = entry[field_name]                               # this sets the field for the first three writes and changes through the fields up above
            writes.append((address, u32_bytes(value), "RDRAM"))     # this will do all three of the first writes before writing the pointer values next

# This second block writes the pointer data, the location the writes need to happen and where to go for the next or previous slot

        next_slot_index = (slot_index + 1) % entry_count                    # next slot INDEX, will wrap from 2 back to 0
        next_pointer = pool_pointer + next_slot_index * INV_ITEM_SIZE       # next slot ADDRESS
        prev_slot_index = (slot_index - 1) % entry_count                    # prev is just the same as above but in reverse
        prev_pointer = pool_pointer + prev_slot_index * INV_ITEM_SIZE

        pointer_fields = [(0x0C, next_pointer), (0x10, prev_pointer)]
        for offset, pointer_value in pointer_fields:                     
            writes.append((slot_address + offset, pointer_bytes(pointer_value), "RDRAM"))      # this will do the last two writes for the startup item, the two pointer writes

    for slot_index in range (entry_count, max_items):              # This range indicates the number of inventory slots left after we've written the loadout, the rest will be cleared
        slot_address = pool_pointer + slot_index * INV_ITEM_SIZE    # where in the game's RAM we're performing the write
        for offset, data in empty_slot_fields:
            writes.append((slot_address + offset, data, "RDRAM"))

## Finally, we tag the writes package with the BONDdata information

    if entry_count > 0:
        head_data = pointer_bytes(pool_pointer)
    else: 
        head_data = pointer_bytes(0)
    writes.append((bonddata_pointer + OFF_INV_HEAD, head_data, "RDRAM"))        # If there are entries, direct the writes to the current pool_pointer for the current BONDdata
    writes.append((bonddata_pointer + OFF_ALL_GUNS, u32_bytes(0), "RDRAM"))     # set all guns to 0
    writes.append((bonddata_pointer + OFF_EQUIP_CUR, u32_bytes(0), "RDRAM"))    # reset current equipped inventory index

    return writes

def build_ammo_writes(loadout):                                 # Prepare ammo info to be granted on loadout
    ammo_writes = []

    for weapon in loadout:
        if weapon["ammo_offset"] is not None:                   # Only ammo for weapons with ammo (i.e. not the hunting knife)
            ammo_writes.append({
                "ammo_offset": weapon["ammo_offset"],
                "ammo_grant": weapon["ammo_grant"],
                "ammo_max": weapon["ammo_max"],
            })
    return ammo_writes

def resolve_progressive_weapon_item_id(progressive_count):
    if progressive_count <= 0:
        return None

    if progressive_count > len(PROGRESSIVE_GUN_ITEM_IDS):
        return None

    return PROGRESSIVE_GUN_ITEM_IDS[progressive_count - 1]


def build_live_inventory_remove_weapon_writes(snapshot, bonddata_pointer, weapon_id):
    writes = []

    for entry in snapshot["entries"]:                                # Find the inventory entry we want to remove
        if entry["type"] == INV_ITEM_WEAPON and entry["weapon_id"] == weapon_id:
            target_entry = entry
            break
    else:
        return writes

    target_pointer = target_entry["pointer"]
    next_pointer = target_entry["next_pointer"]
    prev_pointer = target_entry["prev_pointer"]

    if next_pointer == target_pointer and prev_pointer == target_pointer: # If this was the only inventory entry, empty the list
        writes.append((bonddata_pointer + OFF_INV_HEAD, pointer_bytes(0), "RDRAM"))
    else:
        writes.append((prev_pointer + 0x0C, pointer_bytes(next_pointer), "RDRAM")) # Previous entry now points around this one
        writes.append((next_pointer + 0x10, pointer_bytes(prev_pointer), "RDRAM")) # Next entry now points back around this one
        if snapshot["head_pointer"] == target_pointer:
            writes.append((bonddata_pointer + OFF_INV_HEAD, pointer_bytes(next_pointer), "RDRAM"))

    writes.append((target_pointer + 0x00, s32_bytes(INV_ITEM_NONE), "RDRAM"))       # Clear the removed slot
    writes.append((target_pointer + 0x04, u32_bytes(0), "RDRAM"))
    writes.append((target_pointer + 0x08, u32_bytes(0), "RDRAM"))
    writes.append((target_pointer + 0x0C, pointer_bytes(0), "RDRAM"))
    writes.append((target_pointer + 0x10, pointer_bytes(0), "RDRAM"))

    return writes

def build_live_inventory_add_weapon_writes(snapshot, bonddata_pointer, weapon_id):
    writes = []

    for entry in snapshot["entries"]:                                # Check current inventory so we don't add duplicates
        if entry["type"] == INV_ITEM_WEAPON and entry["weapon_id"] == weapon_id:
            return writes

    if len(snapshot["free_slot_indices"]) == 0:                      # If Bond's inventory is full, don't add anything
        return writes

    pool_pointer = snapshot["pool_pointer"]
    free_slot_index = snapshot["free_slot_indices"][0]
    new_slot_address = pool_pointer + free_slot_index * INV_ITEM_SIZE

    if len(snapshot["entries"]) == 0:                                # If inventory is empty, this new slot points to itself
        next_pointer = new_slot_address
        prev_pointer = new_slot_address
        writes.append((bonddata_pointer + OFF_INV_HEAD, pointer_bytes(new_slot_address), "RDRAM"))
    else:
        head_pointer = snapshot["head_pointer"]                      # First current inventory entry
        tail_pointer = snapshot["entries"][0]["prev_pointer"]        # Previous entry from head is the tail of the circle
        next_pointer = head_pointer
        prev_pointer = tail_pointer
        writes.append((tail_pointer + 0x0C, pointer_bytes(new_slot_address), "RDRAM"))  # Tail now points forward to new slot
        writes.append((head_pointer + 0x10, pointer_bytes(new_slot_address), "RDRAM"))  # Head now points back to new slot

    writes.append((new_slot_address + 0x00, u32_bytes(INV_ITEM_WEAPON), "RDRAM"))
    writes.append((new_slot_address + 0x04, u32_bytes(weapon_id), "RDRAM"))
    writes.append((new_slot_address + 0x08, u32_bytes(0), "RDRAM"))
    writes.append((new_slot_address + 0x0C, pointer_bytes(next_pointer), "RDRAM"))
    writes.append((new_slot_address + 0x10, pointer_bytes(prev_pointer), "RDRAM"))

    return writes

