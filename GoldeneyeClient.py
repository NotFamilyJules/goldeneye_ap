# Write helpers - these are the fundamental functions we need to be able to write values to RAM

def u32_bytes(value):  # unsigned 32bit helper
    return value.to_bytes(4, "big")

def s32_bytes(value):  # signed 32bit helper
    return value.to_bytes(4, "big", signed=True)

def pointer_bytes(value):  # converts a RDRAM address to a game pointer byte value
    if value == 0:
        return u32_bytes(0)    
    value = value + 0x80000000
    return u32_bytes(value)

def rdram_from_pointer(value):  
    # Converts a pointer value from the game into a RDRAM address. 
    # Goldeneye uses like 0x80000000, this adds the 80000000 need to convert it
    if value == 0:
        return 0
    return value - 0x80000000

def to_rdram_ptr(value):
    if value == 0:
        return 0
    if 0 < value < 0x800000:
        return value
    if 0x80000000 <= value < 0x80800000:
        return value - 0x80000000
    return 0

