async def build_live_weapon_receive_writes(ctx, bonddata_pointer, item_id):
    weapon_def = WEAPON_ITEM_DEFS[item_id]
    snapshot = await read_inventory_snapshot(ctx, bonddata_pointer)

    writes = build_live_inventory_add_weapon_writes(snapshot, bonddata_pointer, weapon_def["weapon_id"])

    for extra_id in weapon_def.get("extra_inventory_ids", []):       # Add paired inventory ids like Remote Mine trigger
        writes.extend(build_live_inventory_add_weapon_writes(snapshot, bonddata_pointer, extra_id))

    ammo_offset = weapon_def.get("ammo_offset")
    if ammo_offset is not None:
        ammo_reads = await bizhawk.read(ctx.bizhawk_ctx, [
            (bonddata_pointer + ammo_offset, 4, "RDRAM"),
        ])
        current_ammo = int.from_bytes(ammo_reads[0], "big")
        new_ammo = min(current_ammo + weapon_def["ammo_grant"], weapon_def["ammo_max"])
        writes.append((bonddata_pointer + ammo_offset, u32_bytes(new_ammo), "RDRAM"))

    return writes

async def read_inventory_snapshot(ctx, bonddata_pointer):       # What do bond's inventory be right now

        # head_pointer_address = address
        # reads = raw bytes from BizHawk
        # head_pointer = decoded pointer
        # pool_bytes = raw inventory pool bytes
        # entries = list of parsed active inventory entries
        # free_slot_indices = list of empty slot numbers
        # snapshot = final return dictionary

#~~~~~~ Stage 1: Read the inventory pointers and slot count ~~~~~~#
   
    head_pointer_address = bonddata_pointer + OFF_INV_HEAD      # address where the game stores the head pointer
    pool_pointer_address = bonddata_pointer + OFF_INV_POOL      # address where the game stores the beginning of the inventory pool
    max_items_address = bonddata_pointer + OFF_INV_MAX          # address where the game stores the max inventory slot count

    reads = await bizhawk.read(ctx.bizhawk_ctx, [               # Read inv head, inv pool, inv max from bonddata
    (head_pointer_address, 4, "RDRAM"),
    (pool_pointer_address, 4, "RDRAM"),
    (max_items_address, 4, "RDRAM"),
    ])
    
    head_pointer = int.from_bytes(reads[0], "big")              # Decode the values we just read
    pool_pointer = int.from_bytes(reads[1], "big")
    max_items = int.from_bytes(reads[2], "big")
    
    # Convert head/pool pointers from 0x80000000-based pointers to rdram pointers
    head_pointer = rdram_from_pointer(head_pointer)             # the first active item in the current inventory list
    pool_pointer = rdram_from_pointer(pool_pointer)

 #~~~~~~ Stage 2: Read the whole inventory pool bytes ~~~~~~#

    entries = [] 
    free_slot_indices = []
    
    # Stage transitions can leave inventory unavailable. Bound the native read first.
    if not (0 < pool_pointer and 1 <= max_items <= 128
            and pool_pointer + max_items * INV_ITEM_SIZE <= 0x800000):
        return {                                                # Return the snapshot with the inventory information
            "head_pointer": head_pointer,
            "pool_pointer": pool_pointer,
            "max_items": max_items,
            "entries": entries,
            "free_slot_indices": free_slot_indices,
        }

    pool_size = max_items * INV_ITEM_SIZE                       # How many bytes the full inventory pool takes up
    pool_reads = await bizhawk.read(ctx.bizhawk_ctx, [
        (pool_pointer, pool_size, "RDRAM"),
    ])
    pool_bytes = pool_reads[0]

 #~~~~~~ Stage 3: Walk the active inventory list ~~~~~~#   
    # In this stage, we will fill "entries" by following the active inventory linked list on entry at a time

    current_pointer = head_pointer                                      # Pointer will change as you walk through so new variable, don't just use head_pointer
    seen_pointers = set()                                               # Keeping track of if we've seen the pointer or not so we know when to stop
    while current_pointer > 0 and current_pointer not in seen_pointers: # while works better than for since we just keep going until we've seen this pointer before
        seen_pointers.add(current_pointer)
        relative_offset = current_pointer - pool_pointer                # We need where the current entry starts inside pool_bytes so like if pool_pointer is 1000 and current_pointer is 1040, we get 40
        if relative_offset < 0 or (relative_offset + INV_ITEM_SIZE) > len(pool_bytes):  # just making sure it's actually within pool bytes
            break                                                                       # if so kill it dead

        # Read the current inventory fields, these are in this order in memory known from the decomp documentation
        entry_type = int.from_bytes(pool_bytes[relative_offset + 0x00:relative_offset + 0x04], "big", signed=True)  # Empty inventory slots use -1, which is INV_ITEM_NONE, if we read that as unsigned, -1 would turn into a huge positive number instead of -1
        weapon_id = int.from_bytes(pool_bytes[relative_offset + 0x04:relative_offset + 0x08], "big")                # reads the main weapon/item id stored in this entry
        left_weapon_id = int.from_bytes(pool_bytes[relative_offset + 0x08:relative_offset + 0x0C], "big")           # reads the left-hand weapon id field, usually 0 for normal single weapon entries
        next_pointer = int.from_bytes(pool_bytes[relative_offset + 0x0C:relative_offset + 0x10], "big")             # reads where the next linked inventory entry lives in memory
        prev_pointer = int.from_bytes(pool_bytes[relative_offset + 0x10:relative_offset + 0x14], "big")             # reads where the previous linked inventory entry lives in memory

        next_pointer = rdram_from_pointer(next_pointer) # These have to be converted to rdram relative addresses since that's how this client is reading them
        prev_pointer = rdram_from_pointer(prev_pointer) 

        entries.append({                        # These are the things that describe the active inventory list
            "pointer": current_pointer,         # where the entry exists in memory
            "type": entry_type,                 # what type of entry it is
            "weapon_id": weapon_id,             # what main weapon/item it represents
            "left_weapon_id": left_weapon_id,   # whether it has a left-hand partner or extra id
            "next_pointer": next_pointer,       # how to move forward in the linked list
            "prev_pointer": prev_pointer,       # how the list links backwards
        })
        current_pointer = next_pointer          # setting this loop's current pointer as the next pointer for the next loop

#~~~~~~ Stage 4: Find empty slots ~~~~~~#   
    
    for slot_index in range(max_items):
        slot_start = slot_index * INV_ITEM_SIZE
        entry_type = int.from_bytes(pool_bytes[slot_start:slot_start + 4], "big", signed=True)
        if entry_type == INV_ITEM_NONE: 
            free_slot_indices.append(slot_index)

    snapshot = {
        "head_pointer": head_pointer,
        "pool_pointer": pool_pointer,
        "max_items": max_items,
        "entries": entries,
        "free_slot_indices": free_slot_indices,        
        "guards": [(head_pointer_address, reads[0], "RDRAM"),
                   (pool_pointer_address, reads[1], "RDRAM"),
                   (max_items_address, reads[2], "RDRAM"),
                   (pool_pointer, pool_bytes, "RDRAM")],
    }

    return snapshot

