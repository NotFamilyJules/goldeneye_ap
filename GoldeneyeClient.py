                                await ctx.send_msgs([{                                          # Send location check to AP
                                    "cmd": "LocationChecks",
                                    "locations": [location_id],
                                }])
                                # logger.info(
                                #     "GoldenEye freestanding check sent location_id=%d location_name=%s",
                                #     location_id,
                                #     location_name,
                                # )
